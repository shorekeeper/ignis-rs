//! 8x8 monospace bitmap font.
//!
//! Hand-authored printable ASCII subset including separate uppercase and
//! lowercase letterforms. Each glyph is 8 rows of 8 bits with bit 7 as
//! the leftmost pixel. Characters not in the table render as a solid
//! block, which makes accidental usage visually obvious.
//!
//! Letterforms loosely follow the IBM PC CGA 8x8 character ROM aesthetics:
//! uppercase letters are 7 pixels tall with top-aligned baseline,
//! lowercase letters are 5 pixels tall with descenders for `g j p q y`
//! that extend into the bottom row.
//!
//! Total table size: about 1.4 KiB. Embedded directly in code.

/// Look up the 8 bytes that draw the given character.
pub fn glyph_bytes(c: char) -> [u8; 8] {
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .map(|(_, bytes)| *bytes)
        .unwrap_or(UNKNOWN)
}

