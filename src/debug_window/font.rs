#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_chars_have_glyphs() {
        for c in "ABCXYZabcxyz0123456789".chars() {
            let g = glyph_bytes(c);
            assert_ne!(g, UNKNOWN, "missing glyph for {c}");
        }
    }

    #[test]
    fn lowercase_distinct_from_uppercase() {
        // Now that lowercase has its own glyphs, 'a' must NOT equal 'A'.
        assert_ne!(glyph_bytes('a'), glyph_bytes('A'));
        assert_ne!(glyph_bytes('z'), glyph_bytes('Z'));
        assert_ne!(glyph_bytes('m'), glyph_bytes('M'));
    }

    #[test]
    fn descenders_extend_to_last_row() {
        // g, j, p, q, y all have ink in row 7 (the descender row).
        for c in ['g', 'j', 'p', 'q', 'y'] {
            let g = glyph_bytes(c);
            assert_ne!(g[7], 0x00, "char '{c}' missing descender row");
        }
    }

    #[test]
    fn uppercase_has_no_descenders() {
        // Uppercase letters keep their last row clear.
        for c in ['A', 'B', 'C', 'O', 'X', 'Z'] {
            let g = glyph_bytes(c);
            assert_eq!(g[7], 0x00, "char '{c}' should not have a descender");
        }
    }

    #[test]
    fn unknown_returns_block() {
        assert_eq!(glyph_bytes('Ω'), UNKNOWN);
        assert_eq!(glyph_bytes('\u{1F600}'), UNKNOWN);
    }

    #[test]
    fn space_is_blank() {
        assert_eq!(glyph_bytes(' '), [0; 8]);
    }
}